CREATE TABLE dry_docks (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  dry_dock_no VARCHAR(50) NOT NULL UNIQUE,
  vessel_id BIGINT UNSIGNED NOT NULL,
  shipyard_id BIGINT UNSIGNED NULL,
  title VARCHAR(190) NOT NULL,
  description TEXT NULL,
  account_code VARCHAR(50) NULL,
  responsible_rank VARCHAR(100) NULL,
  currency CHAR(3) NOT NULL DEFAULT 'USD',
  budget DECIMAL(15, 2) NOT NULL DEFAULT 0,
  yard_estimates DECIMAL(15, 2) NOT NULL DEFAULT 0,
  owner_estimates DECIMAL(15, 2) NOT NULL DEFAULT 0,
  actual_yard_costs DECIMAL(15, 2) NOT NULL DEFAULT 0,
  actual_owner_costs DECIMAL(15, 2) NOT NULL DEFAULT 0,
  priority ENUM('LOW', 'MEDIUM', 'HIGH') NOT NULL DEFAULT 'MEDIUM',
  status ENUM('PLANNING', 'EXECUTION', 'COMPLETED') NOT NULL DEFAULT 'PLANNING',
  planned_start_date DATE NULL,
  planned_end_date DATE NULL,
  actual_start_date DATE NULL,
  actual_end_date DATE NULL,
  spec_version INT UNSIGNED NOT NULL DEFAULT 0,
  spec_exported_at DATETIME NULL,
  created_by BIGINT UNSIGNED NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  deleted_at TIMESTAMP NULL,
  FOREIGN KEY (vessel_id) REFERENCES vessels (id),
  FOREIGN KEY (shipyard_id) REFERENCES shipyards (id) ON DELETE SET NULL,
  FOREIGN KEY (created_by) REFERENCES users (id) ON DELETE SET NULL,
  INDEX idx_dd_status (status),
  INDEX idx_dd_vessel (vessel_id)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_unicode_ci;